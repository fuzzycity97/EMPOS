/// Clinical Classification of Medical & Surgical Instruments
enum ClinicalInstrumentCategory {
  diagnostic('Diagnostic & Screening', 'تشخيصي وفحص سريري', Color(0xFF0284C7)),
  procedural('Procedural & Interventional', 'إجرائي وتداخلي', Color(0xFFF59E0B)),
  surgical('Surgical & Operative', 'جراحي وعمليات', Color(0xFFEF4444)),
  assessment('Diagnostic & Assessment Scales', 'مقاييس تقييم وتشخيص', Color(0xFF8B5CF6));

  final String titleEn;
  final String titleAr;
  final Color color;
  const ClinicalInstrumentCategory(this.titleEn, this.titleAr, this.color);

  String get localizedTitle => AppLanguage.isArabic ? titleAr : titleEn;
}

/// Clinical Instrument Specification for Specialty Workbenches & 3D Trays
class ClinicalInstrumentItem {
  final String id;
  final String nameEn;
  final String nameAr;
  final ClinicalInstrumentCategory category;
  final String descriptionEn;
  final String descriptionAr;
  final IconData icon;
  final bool isNonInvasive;

  const ClinicalInstrumentItem({
    required this.id,
    required this.nameEn,
    required this.nameAr,
    required this.category,
    required this.descriptionEn,
    required this.descriptionAr,
    this.icon = LucideIcons.wrench,
    this.isNonInvasive = false,
  });

  String get localizedName => AppLanguage.isArabic ? nameAr : nameEn;
  String get localizedDescription => AppLanguage.isArabic ? descriptionAr : descriptionEn;
}

/// Specialty Registry Profile Entry mapping a medical discipline to its full instrument set
class SpecialtyRegistryEntry {
  final ClinicalSpecialtyDiscipline discipline;
  final int groupNumber;
  final String groupNameEn;
  final String groupNameAr;
  final String specialtyNameEn;
  final String specialtyNameAr;
  final List<ClinicalInstrumentItem> tools;
  final bool isAssessmentDriven;
  final String? clinicalNotesEn;
  final String? clinicalNotesAr;

  const SpecialtyRegistryEntry({
    required this.discipline,
    required this.groupNumber,
    required this.groupNameEn,
    required this.groupNameAr,
    required this.specialtyNameEn,
    required this.specialtyNameAr,
    required this.tools,
    this.isAssessmentDriven = false,
    this.clinicalNotesEn,
    this.clinicalNotesAr,
  });

  String get localizedGroupName => AppLanguage.isArabic ? groupNameAr : groupNameEn;
  String get localizedSpecialtyName => AppLanguage.isArabic ? specialtyNameAr : specialtyNameEn;
  String? get localizedClinicalNotes => AppLanguage.isArabic ? clinicalNotesAr : clinicalNotesEn;
}

