  /// Returns the exhaustive registry entry for the given specialty discipline.
  static SpecialtyRegistryEntry getEntry(ClinicalSpecialtyDiscipline discipline) {
    return _registry[discipline] ?? _registry[ClinicalSpecialtyDiscipline.general]!;
  }

  /// Returns the exhaustive list of tools / instruments for the given specialty discipline.
  static List<ClinicalInstrumentItem> getToolsForDiscipline(ClinicalSpecialtyDiscipline discipline) {
    return getEntry(discipline).tools;
  }

  /// Filters tools for a discipline by their clinical category (diagnostic, procedural, surgical, assessment).
  static List<ClinicalInstrumentItem> getToolsByCategory(
    ClinicalSpecialtyDiscipline discipline,
    ClinicalInstrumentCategory category,
  ) {
    return getToolsForDiscipline(discipline).where((tool) => tool.category == category).toList();
  }

  /// Returns all registered specialty entries across all disciplines.
  static List<SpecialtyRegistryEntry> get allEntries => _registry.values.toList();
