/// Comprehensive, granular registry cataloging all gateable capabilities across
/// all 11 industry verticals and 41 specific business blueprints.
class CapabilityRegistry {
  static final CapabilityRegistry _instance = CapabilityRegistry._internal();
  static CapabilityRegistry get instance => _instance;

  final Map<String, CapabilityItem> _items = {};

  CapabilityRegistry._internal() {
    _initializeAllCapabilities();
  }

  /// Returns an unmodifiable list of all registered capabilities.
  List<CapabilityItem> get allCapabilities => List.unmodifiable(_items.values);

  /// Total count of granular capabilities registered in the ecosystem.
  int get count => _items.length;

  /// Looks up a capability by its unique identifier.
  CapabilityItem? getCapability(String id) => _items[id];

  /// Checks if a capability exists in the registry.
  bool contains(String id) => _items.containsKey(id);

  /// Returns all capabilities belonging to a specific functional category.
  List<CapabilityItem> getByCategory(CapabilityCategory category) {
    return _items.values.where((item) => item.category == category).toList();
  }

  /// Returns all capabilities relevant to an industry vertical (including universal ones).
  List<CapabilityItem> getByVertical(IndustryVertical vertical) {
    return _items.values
        .where((item) => item.vertical == null || item.vertical == vertical)
        .toList();
  }

  /// Returns all universal cross-vertical capabilities.
  List<CapabilityItem> getUniversalCapabilities() {
    return _items.values.where((item) => item.vertical == null).toList();
  }

  /// Rule B: Search capabilities by query string across name, id, category, vertical, and tags.
  List<CapabilityItem> search(String query) {
    if (query.trim().isEmpty) return allCapabilities;
    return _items.values.where((item) => item.matchesSearch(query)).toList();
  }

  /// Registers or updates a capability item dynamically at runtime.
  void register(CapabilityItem item) {
    _items[item.id] = item;
  }

  /// Predefined tier presets bundling capabilities.
  SubscriptionTierPreset getPreset(SubscriptionPlanTier tier) {
    switch (tier) {
      case SubscriptionPlanTier.free:
        return SubscriptionTierPreset(
          tier: SubscriptionPlanTier.free,
          name: 'Free Starter Preset',
          description: 'Minimal operations: single terminal, offline persistence, basic booking & checkout',
          includedCapabilityIds: _resolveTierCapabilities(SubscriptionPlanTier.free),
          includesAllByDefault: false,
          maxTerminals: 1,
          maxStaffAccounts: 2,
        );

      case SubscriptionPlanTier.basic:
        return SubscriptionTierPreset(
          tier: SubscriptionPlanTier.basic,
          name: 'Basic Operations Preset',
          description: 'Core operations: LAN multi-device sync, basic inventory, conflict guard & split tender',
          includedCapabilityIds: _resolveTierCapabilities(SubscriptionPlanTier.basic),
          includesAllByDefault: false,
          maxTerminals: 3,
          maxStaffAccounts: 10,
        );

      case SubscriptionPlanTier.pro:
        return SubscriptionTierPreset(
          tier: SubscriptionPlanTier.pro,
          name: 'Professional Specialty Preset',
          description: 'Full specialty tools: 3D clinical actions, FEFO tracking, multi-party splits & KDS',
          includedCapabilityIds: _resolveTierCapabilities(SubscriptionPlanTier.pro),
          includesAllByDefault: false,
          maxTerminals: 10,
          maxStaffAccounts: 50,
        );

      case SubscriptionPlanTier.enterprise:
        return const SubscriptionTierPreset(
          tier: SubscriptionPlanTier.enterprise,
          name: 'Enterprise Unrestricted Preset',
          description: 'Unrestricted ecosystem access: auto-unlocks all existing and future capabilities',
          includedCapabilityIds: <String>{},
          includesAllByDefault: true, // Auto-unlocks everything!
          maxTerminals: 9999,
          maxStaffAccounts: 9999,
        );

      case SubscriptionPlanTier.custom:
        return SubscriptionTierPreset(
          tier: SubscriptionPlanTier.custom,
          name: 'Custom Operator Preset',
          description: 'Individually tailored tier based on Basic with custom overrides',
          includedCapabilityIds: _resolveTierCapabilities(SubscriptionPlanTier.basic),
          includesAllByDefault: false,
          maxTerminals: 5,
          maxStaffAccounts: 20,
        );
    }
  }

  Set<String> _resolveTierCapabilities(SubscriptionPlanTier tier) {
    final set = <String>{};
    for (final item in _items.values) {
      if (item.isRequiredCompliance) {
        set.add(item.id);
        continue;
      }
      if (tier.isAtLeast(item.minTier)) {
        set.add(item.id);
      }
    }
    return set;
  }

